/**
 * Evaluate position relative to `turn` (positive = good for turn's side).
 */
export function evaluate(board, turn) {
  let score = 0;
  for (let r = 0; r < 8; r++) {
    for (let c = 0; c < 8; c++) {
      const piece = board[r][c];
      if (!piece) continue;
      const color = piece[0];
      const type = piece[1];
      const value = PIECE_VALUES[type] || 0;
      // PST: white uses row as-is (rank 8 = row 0), black mirrors vertically
      const pstRow = color === 'w' ? r : 7 - r;
      const pst = PST[type] ? PST[type][pstRow][c] : 0;
      const pieceScore = value + pst;
      score += color === turn ? pieceScore : -pieceScore;
    }
  }
  return score;
}
